function getCardChoices() {
  const correct = flashcards[cardIndex][1];
  const distractors = flashcards
    .filter((_, index) => index !== cardIndex)
    .map((card) => card[1])
    .sort(() => Math.random() - 0.5)
    .slice(0, 3);

  return [correct, ...distractors]
    .sort(() => Math.random() - 0.5)
    .map((text) => ({ text, correct: text === correct }));
}

function renderCardChoices() {
  $("#cardChoices").innerHTML = getCardChoices()
    .map(
      (choice, index) => `
        <button class="card-choice" data-choice="${index}" data-correct="${choice.correct}">
          ${choice.text}
        </button>
      `
    )
    .join("");
}

function shuffleCards() {
  for (let i = flashcards.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [flashcards[i], flashcards[j]] = [flashcards[j], flashcards[i]];
  }
  cardIndex = 0;
  flipped = false;
  renderCard();
}

function checkCardAnswer() {
  const userAnswer = $("#cardAnswer").value;
  const expected = flashcards[cardIndex][1];
  const expectedKeywords = [...new Set(getKeywords(expected))];
  const userWords = new Set(getKeywords(userAnswer));
  const hits = expectedKeywords.filter((word) => userWords.has(word));
  const minimum = Math.max(1, Math.ceil(expectedKeywords.length * 0.35));
  const feedback = $("#answerFeedback");

  if (!userAnswer.trim()) {
    feedback.textContent = "Escribí una respuesta antes de comprobar.";
    feedback.className = "answer-feedback warning";
    return;
  }

  if (hits.length >= minimum) {
    feedback.textContent = `Bien encaminada: coincidiste con ${hits.length} idea(s) clave. Ahora compará con la respuesta.`;
    feedback.className = "answer-feedback good";
  } else {
    feedback.textContent = `Te faltan ideas clave. Coincidencias: ${hits.length}. Mirá la respuesta y probá reformularla.`;
    feedback.className = "answer-feedback bad";
  }

  flipped = true;
  renderCard(false);
}

