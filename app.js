function getQuestionTopic(question) {
  const text = normalizeText(question.q || question);
  if (/(constitucion|constitucional|convencionalidad|supremacia|reforma|poder constituyente)/.test(text)) return "Constitución y controles";
  if (/(guariglia|publico|privado|globalizacion|estado|sociedad)/.test(text)) return "Estado y sociedad";
  if (/(moral|social|juridica|norma|derecho objetivo|derecho subjetivo|coercion)/.test(text)) return "Normas";
  if (/(risso|jimenez|correa|interpretacion)/.test(text)) return "Autores";
  return "Repaso general";
}

function recordWeakTopic(question) {
  const topic = getQuestionTopic(question);
  weakTopics[topic] = (weakTopics[topic] || 0) + 1;
}

function getWeakestTopic() {
  const entries = Object.entries(weakTopics).sort((a, b) => b[1] - a[1]);
  return entries.length ? entries[0][0] : "Sin datos";
}

function getTopicCategory(topic) {
  const title = normalizeText(topic.title);
  if (/(guariglia|risso|jimenez|correa)/.test(title)) return "Autores y enfoques";
  if (/(caso|legitimacion|gobiernos|personas publicas)/.test(title)) return "Casos e instituciones";
  if (/(control|constitucionalidad|convencionalidad|supremacia|reforma|poder constituyente)/.test(title)) return "Control y Constitución";
  if (/(derecho publico|globalizacion|estado|sociedad)/.test(title)) return "Estado y sociedad";
  return "Conceptos base";
}

function renderTopics(filter = "") {
  const grid = $("#topicGrid");
  const text = filter.trim().toLowerCase();
  const filtered = topics.filter((topic) =>
    `${topic.title} ${topic.points.join(" ")}`.toLowerCase().includes(text)
  );
  const grouped = filtered.reduce((acc, topic) => {
    const category = getTopicCategory(topic);
    if (!acc[category]) acc[category] = [];
    acc[category].push(topic);
    return acc;
  }, {});

  grid.innerHTML = Object.entries(grouped)
    .map(([category, items]) => `
      <div class="topic-section">
        <h3 class="topic-section-title">${category}</h3>
        <div class="topic-section-grid">
          ${items.map((topic) => `
            <article class="topic-card">
              <h3>${topic.title}</h3>
              <ul>${topic.points.map((point) => `<li>${point}</li>`).join("")}</ul>
            </article>
          `).join("")}
        </div>
      </div>
    `)
    .join("");
}

