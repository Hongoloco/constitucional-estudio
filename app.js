function normalizeText(text) {
  return text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^\w\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function getKeywords(text) {
  const stopwords = new Set([
    "una", "uno", "unas", "unos", "que", "por", "para", "con", "del", "las", "los",
    "como", "desde", "esta", "este", "tiene", "gracias", "donde", "cual", "cada",
    "segun", "sobre", "entre", "porque", "puede", "debe", "ser", "son", "sus",
    "mas", "menos", "forma", "regla", "norma", "derecho"
  ]);

  return normalizeText(text)
    .split(" ")
    .filter((word) => word.length > 3 && !stopwords.has(word));
}

