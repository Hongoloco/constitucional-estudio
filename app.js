function handleMatch(target) {
  if (target.dataset.term) {
    selectedMatch = target.dataset.term;
    document.querySelectorAll("[data-term]").forEach((item) => item.classList.remove("selected"));
    target.classList.add("selected");
    return;
  }

  if (!selectedMatch || !target.dataset.def) return;

  if (selectedMatch === target.dataset.def) {
    matched.add(selectedMatch);
    document.querySelector(`[data-term="${selectedMatch}"]`).classList.add("correct");
    target.classList.add("correct");
    selectedMatch = null;
  } else {
    target.classList.add("wrong");
    setTimeout(() => target.classList.remove("wrong"), 500);
  }

  $("#matchScore").textContent = `${matched.size}/${matches.length}`;
  updateProgress();
}

