async function copyPrompt(index, button) {
  const prompt = notebookPrompts[index];
  try {
    await navigator.clipboard.writeText(prompt);
    button.querySelector("small").textContent = "Copiado";
  } catch {
    button.querySelector("small").textContent = "Seleccioná y copiá";
  }
  setTimeout(() => {
    button.querySelector("small").textContent = "Copiar";
  }, 1200);
}

function startSpeed() {
  clearInterval(timerId);
  speedIndex = 0;
  speedScore = 0;
  timeLeft = 45;
  $("#timer").textContent = `${timeLeft}s`;
  timerId = setInterval(() => {
    timeLeft -= 1;
    $("#timer").textContent = `${timeLeft}s`;
    if (timeLeft <= 0) {
      clearInterval(timerId);
      timerId = null;
      renderSpeed(`Tiempo terminado. Puntaje final: ${speedScore}.`);
    }
  }, 1000);
  renderSpeed();
}

function answerSpeed(value) {
  if (!timerId) return;
  const correct = speedFacts[speedIndex % speedFacts.length][1] === value;
  speedScore += correct ? 1 : -1;
  speedIndex += 1;
  renderSpeed();
}

